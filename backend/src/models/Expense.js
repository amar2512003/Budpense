import mongoose from "mongoose";

import { EXPENSE, RECORD_TYPES } from "../constants/enums.js";
import entryFields from "./entryFields.js";

// One collection holds both sides of the ledger, separated by type. Income has
// a source where an expense has a category, and carries neither a title nor a
// payment method — the income form asks for neither.
const expenseSchema = new mongoose.Schema(
  {
    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
    type: {
      type: String,
      enum: RECORD_TYPES,
      default: EXPENSE,
      required: true,
    },
    ...entryFields,
    date: {
      type: Date,
      required: [true, "Date is required"],
    },
    // Set on entries generated by a recurring rule.
    recurring: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Recurring",
    },
  },
  { timestamps: true },
);

// Every list query filters by user and type and sorts by date descending, so
// this covers the common read end to end without touching the documents.
expenseSchema.index({ user: 1, type: 1, date: -1 });

// A rule produces at most one entry per date. This is what makes generation
// safe to repeat after a crash or when two runs overlap.
expenseSchema.index(
  { recurring: 1, date: 1 },
  { unique: true, partialFilterExpression: { recurring: { $exists: true } } },
);

export default mongoose.model("Expense", expenseSchema);
